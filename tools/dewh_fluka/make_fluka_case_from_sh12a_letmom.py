def parse_detect_meshes(path):
    """
    Parse geometry mesh definitions from SHIELD-HIT `detect.dat`.

    The benchmark uses SHIELD-HIT detector meshes to define scoring regions.
    For the FLUKA comparison workflow, the most important one is usually:

        Z_narrow

    which corresponds to the central narrow scoring channel along depth.

    This parser extracts mesh names and their X/Y/Z ranges:

        X = (min, max, number_of_bins)
        Y = (min, max, number_of_bins)
        Z = (min, max, number_of_bins)

    and returns a dictionary:

        mesh_name -> mesh_definition
    """

    meshes = {}
    lines = path.read_text().splitlines()
    i = 0

    while i < len(lines):
        # Remove inline comments and whitespace before checking the block type.
        line = lines[i].split("#", 1)[0].strip()

        # We only parse "Geometry Mesh" blocks here.
        if line != "Geometry Mesh":
            i += 1
            continue

        # Start a new mesh block.
        mesh = {"name": None}
        i += 1

        while i < len(lines):
            sub = lines[i].split("#", 1)[0].strip()

            # Blank line ends the current mesh block.
            if not sub:
                i += 1
                break

            # These keywords mark the beginning of another detect.dat block.
            if sub in ("Geometry Mesh", "Filter", "Settings", "Output"):
                break

            parts = sub.split()

            if parts and parts[0] == "Name":
                mesh["name"] = parts[1]

            elif parts and parts[0] in ("X", "Y", "Z") and len(parts) >= 4:
                # Store coordinate limits and number of bins.
                mesh[parts[0]] = (
                    float(parts[1]),
                    float(parts[2]),
                    int(float(parts[3])),
                )

            i += 1

        if mesh.get("name"):
            meshes[mesh["name"]] = mesh

    return meshes


