def parse_mat_dat(path):
    """
    Parse SHIELD-HIT `mat.dat` medium blocks for documentation/provenance.

    The generated FLUKA input uses a fixed material mapping for the current
    benchmark workflow, but we still parse the original SHIELD-HIT material file
    so the generated case can record what material definitions were present in
    the source case.

    The function returns a list of dictionaries, one per MEDIUM block:

        {
            "id": material/medium id,
            "comment": inline comment after the MEDIUM line,
            "lines": original material lines inside the block
        }
    """

    media = []
    current = None

    for raw in path.read_text().splitlines():
        stripped = raw.strip()

        if not stripped:
            continue

        # Split each line into the parseable part and optional comment.
        no_comment = stripped.split("#", 1)[0].strip()
        comment = stripped.split("#", 1)[1].strip() if "#" in stripped else ""

        if no_comment.startswith("MEDIUM"):
            # Start of a new SHIELD-HIT material/medium block.
            parts = no_comment.split()
            current = {"id": parts[1], "comment": comment, "lines": []}
            media.append(current)

        elif no_comment == "END":
            # End of the current material/medium block.
            current = None

        elif current is not None:
            # Preserve the original line for the manifest.
            current["lines"].append(stripped)

    return media


