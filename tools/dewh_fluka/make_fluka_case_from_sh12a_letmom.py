def strip_comment(line):
    """
    Remove an inline SHIELD-HIT comment and surrounding whitespace.

    SHIELD-HIT input files often use `#` for comments. For parsing numerical
    and keyword fields, we only want the part before the comment.
    """

    return line.split("#", 1)[0].strip()


def parse_beam_dat(path):
    """
    Parse the simple key-value structure of SHIELD-HIT `beam.dat`.

    The resulting dictionary maps the first token on each non-comment line to
    the remaining tokens.

    Example structure:
        key -> [value1, value2, ...]

    The exact physics meaning of the entries is handled later when specific
    beam/source parameters are inserted into the FLUKA input.
    """

    data = {}

    for raw in path.read_text().splitlines():
        line = strip_comment(raw)

        # Skip blank lines and SHIELD-HIT-style comment/control lines.
        if not line or line.startswith("*"):
            continue

        parts = line.split()
        key = parts[0]
        vals = parts[1:]

        data[key] = vals

    return data


