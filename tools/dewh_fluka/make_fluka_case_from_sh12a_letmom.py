def sha256(path):
    """
    Compute the SHA256 checksum of a file.

    Checksums are written into CASE_MANIFEST.txt so generated cases can be
    traced back to the exact input/source files used at generation time.
    """

    h = hashlib.sha256()

    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)

    return h.hexdigest()

